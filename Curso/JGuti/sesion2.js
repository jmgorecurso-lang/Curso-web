// vamos con Switch
let nivel = 1;
switch (nivel){
    case 1:
        console.log("Nivel 1");
        break;
    case 2:
        console.log("Nivel 2");
        break;
    case 3:
        console.log("Nivel 3");
        break;
    case 4:
        console.log("Nivel 4");
        break;
    case 5:
        console.log("Nivel 5");
        break;
    case 6:
        console.log("Nivel 6");
        break;
    case 7:
        console.log("Nivel 7");
        break;
        default:
            console.log("ingreso no valido");
            break;
}